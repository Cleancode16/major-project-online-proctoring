"""
Run the whole test suite and write tests/results/SUMMARY.md.

  .venv\\Scripts\\python.exe -m tests.run_all            # all tests
  .venv\\Scripts\\python.exe -m tests.run_all --quick    # skip the slow calibrations (use cached results)

Test data: the real sample clip + reference photo (candidate's own recordings), public LFW pairs and
Mini LibriSpeech (downloaded once), and SYNTHETIC clips/audio generated by tests/make_synthetic_*.py.
"""

import argparse
import json
import subprocess
import sys
import time

from tests import paths

GENERATORS = ["tests.make_synthetic_video", "tests.make_synthetic_audio"]
TESTS = [
    ("R1 legacy equivalence", "tests.test_r1_legacy_equivalence"),
    ("V1 head pose", "tests.test_v1_head_pose"),
    ("V2-V4 sampling/calibration/pose", "tests.test_v2_v4_sampling_calibration_pose"),
    ("V5 gaze", "tests.test_v5_gaze"),
    ("V6 face verification", "tests.test_v6_face"),
    ("V7/V8 persons/objects", "tests.test_v7_v8_scene"),
    ("HP2/GZ2 head pose + gaze accuracy", "tests.test_hp2_pose_gaze"),
    ("GZ3 L2CS-Net gaze", "tests.test_gz3_l2cs"),
    ("PERF1 torch thread count", "tests.test_perf1_threads"),
    ("PERF2 YOLO stride", "tests.test_perf2_yolo_stride"),
    ("DET2 persons / objects / gaze calibration", "tests.test_det2_persons_objects"),
    ("FAS1 face anti-spoofing", "tests.test_fas1_antispoof"),
    ("VAD2/MP2/OB2 voice, persons, objects accuracy", "tests.test_vad2_mp2_ob2"),
    ("A1/A2 audio I/O + VAD", "tests.test_a1_a2_audio_vad"),
    ("A3 voice enrollment", "tests.test_a3_enrollment"),
    ("A4-A6 audio monitor", "tests.test_a4_a6_audio_monitor"),
    ("G1 aggregation", "tests.test_g1_aggregation"),
    ("T2 end-to-end", "tests.test_e2e"),
    ("server.py regression", "tests.test_server_regression"),
]
SLOW = [("V6 LFW calibration", "tests.calibrate_face_threshold"),
        ("A5 LibriSpeech calibration", "tests.calibrate_speaker_threshold")]


def run(module):
    t0 = time.time()
    p = subprocess.run([sys.executable, "-m", module], capture_output=True, text=True, cwd=paths.ROOT,
                       env={**__import__("os").environ, "TF_CPP_MIN_LOG_LEVEL": "2", "PYTHONIOENCODING": "utf-8"})
    lines = [ln for ln in p.stdout.splitlines() if ln.strip()]
    return p.returncode, round(time.time() - t0, 1), lines


def detector_table():
    rows = []
    for name, f in (("v1 (legacy)", "eval_sample_legacy.json"), ("v2", "eval_sample_v2.json")):
        p = paths.RESULTS / f
        if p.exists():
            d = json.loads(p.read_text())
            for t, s in d["scores"].items():
                rows.append(f"| real clip | {t} | {name} | {s['TP']} | {s['FP']} | {s['FN']} | {s['TN']} |")
    p = paths.RESULTS / "V9_noface_v2.json"
    if p.exists():
        s = json.loads(p.read_text())["scores"]["FACE_NOT_VISIBLE"]
        rows.append(f"| SYNTHETIC no-face clip | FACE_NOT_VISIBLE | v2 | {s['TP']} | {s['FP']} | {s['FN']} | {s['TN']} |")
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    a = ap.parse_args()
    results = []
    for g in GENERATORS:
        code, secs, _ = run(g)
        print(f"generator {g}: exit {code} ({secs}s)")
    # refresh the per-detector metrics used in SUMMARY.md
    for args in (["--profile", "legacy", "--out", "tests/results/eval_sample_legacy.json"],
                 ["--profile", "v2", "--out", "tests/results/eval_sample_v2.json"],
                 ["--profile", "v2", "--video", "tests/data/synthetic/noface_clip.mp4", "--labels",
                  "tests/data/synthetic/noface_clip.labels.json", "--out", "tests/results/V9_noface_v2.json"]):
        p = subprocess.run([sys.executable, "-m", "tests.eval_video", *args], capture_output=True, text=True,
                           cwd=paths.ROOT)
        print(f"metrics eval_video {args[1]} -> {args[-1]}: exit {p.returncode}")
    if not a.quick:
        for name, mod in SLOW:
            code, secs, lines = run(mod)
            results.append((name, mod, code, secs, lines[-1] if lines else ""))
            print(f"{'PASS' if code == 0 else 'FAIL'} {name} ({secs}s)")
    for name, mod in TESTS:
        code, secs, lines = run(mod)
        results.append((name, mod, code, secs, lines[-1] if lines else ""))
        print(f"{'PASS' if code == 0 else 'FAIL'} {name} ({secs}s) - {lines[-1] if lines else ''}")
        (paths.RESULTS / f"log_{mod.split('.')[-1]}.txt").write_text("\n".join(lines), encoding="utf-8")

    md = [f"# Test summary ({time.strftime('%Y-%m-%d %H:%M')})", "",
          "| Test | Module | Result | Seconds | Last line |", "|---|---|---|---|---|"]
    for name, mod, code, secs, last in results:
        md.append(f"| {name} | `{mod}` | {'PASS' if code == 0 else 'FAIL'} | {secs} | {last.replace('|', '/')} |")
    md += ["", "## Per-detector sample counts", "", "| Data | Violation | Version | TP | FP | FN | TN |",
           "|---|---|---|---|---|---|---|"] + detector_table()
    md += ["", "Audio window-level results (SYNTHETIC scenes) are in `log_test_a4_a6_audio_monitor.txt`; "
           "LFW / LibriSpeech calibration numbers in `V6_face_calibration.json` / `A5_speaker_calibration.json`."]
    (paths.RESULTS / "SUMMARY.md").write_text("\n".join(md), encoding="utf-8")
    failed = [r for r in results if r[2] != 0]
    print(f"\n{len(results) - len(failed)}/{len(results)} passed. Summary: tests/results/SUMMARY.md")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
